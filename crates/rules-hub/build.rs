// Embeds the built interface (`ui/dist`) into the binary.
//
// A build without `ui/dist` embeds nothing and the hub shows its placeholder
// page; a build with it serves the interface from memory with no file to
// find at run time. The files are the same as `src/ui.rs` accepts: the
// `index.html` and the files directly in `assets/`, plain names, a short
// list of types, none over 4 MiB.
//
// Cargo decides by modification times whether to run a build script again.
// A folder that was moved back into place keeps an old time, and the binary
// would then carry the interface of an earlier build. So this script is run
// by every build (it names a path that is never there, which cargo counts as
// changed), and what it writes holds a hash of the files: the crate is built
// again exactly when the interface differs.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const MAX_FILE: u64 = 4 * 1024 * 1024;

fn content_type(path: &Path) -> Option<&'static str> {
    let ext = path.extension()?.to_str()?.to_ascii_lowercase();
    Some(match ext.as_str() {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        _ => return None,
    })
}

fn plain_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 128
        && !name.starts_with('.')
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
}

/// FNV-1a, 64 bit: a fingerprint of the files, not a security measure.
fn fnv(hash: &mut u64, bytes: &[u8]) {
    for b in bytes {
        *hash ^= u64::from(*b);
        *hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
}

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let dist = manifest.join("..").join("..").join("ui").join("dist");
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("out dir")).join("ui_embedded.rs");
    // A path that is not there: always "changed", so always run (see above).
    println!("cargo:rerun-if-changed=ui-dist-is-looked-at-by-every-build");

    // The icon of the program, which Explorer shows and a link takes from its target. The file is
    // the compiled resource the icon generator writes; the linker of MSVC takes it as it is.
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        let res = manifest
            .join("..")
            .join("..")
            .join("assets")
            .join("rules-desktop.res");
        println!("cargo:rerun-if-changed={}", res.display());
        println!("cargo:rustc-link-arg-bins={}", res.display());
    }

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    if dist.join("index.html").is_file() {
        entries.push(("index.html".to_owned(), dist.join("index.html")));
        if let Ok(dir) = std::fs::read_dir(dist.join("assets")) {
            for entry in dir.flatten() {
                let name = entry.file_name().to_string_lossy().into_owned();
                if plain_name(&name)
                    && entry.path().is_file()
                    && content_type(&entry.path()).is_some()
                {
                    entries.push((format!("assets/{name}"), entry.path()));
                }
            }
        }
    }
    entries.sort();

    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    let mut body = String::new();
    for (key, path) in &entries {
        let bytes = std::fs::read(path).expect("read an interface file");
        assert!(
            (bytes.len() as u64) <= MAX_FILE,
            "{} is larger than {MAX_FILE} bytes",
            path.display()
        );
        fnv(&mut hash, key.as_bytes());
        fnv(&mut hash, &bytes);
        let canonical = path.canonicalize().unwrap_or_else(|_| path.clone());
        let kind = content_type(path).expect("checked above");
        // `{:?}` escapes backslashes and quotes of a Windows path.
        writeln!(
            body,
            "    ({key:?}, {kind:?}, include_bytes!({:?})),",
            canonical.display().to_string()
        )
        .expect("write to a string");
    }

    let mut code = String::new();
    writeln!(
        code,
        "// generated by build.rs; the files hash to {hash:016x}"
    )
    .expect("string");
    code.push_str("pub static EMBEDDED: &[(&str, &str, &[u8])] = &[\n");
    code.push_str(&body);
    code.push_str("];\n");

    // Written only when it differs: an unchanged file does not make the
    // crate build again.
    if std::fs::read_to_string(&out).ok().as_deref() != Some(code.as_str()) {
        std::fs::write(out, code).expect("write the embedded table");
    }
}
